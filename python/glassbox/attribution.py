"""Which SAE features made the model predict a token? Cheap estimates, checked against ablation.

    python -m glassbox.attribution        # -> results/attribution.{json,md}

Setting: the model reads tokens ids[0..t] and predicts the next token y at position t. Candidates
are the SAE features active at the last WINDOW positions (t - WINDOW + 1 .. t), at the SAE's layer.
Feature f at position p contributes act * d_f to the residual stream there (d_f = W_dec[f] / scale).

Ground truth (ablation): subtract act * d_f at position p, run the rest of the model, and take the
drop in y's logit at t: effect = logit(clean) - logit(ablated).

Estimates, each a number per candidate:
  * direct logit attribution (DLA): the feature's contribution along the direct residual path to the
    unembedding, act * ((d_f - mean(d_f)) / sigma_t * ln_f.weight) . wte[y], with sigma_t the ln_f
    scale at t. It ignores the later blocks, and is 0 for p < t (no direct path to position t).
  * gradient x activation: act * (d logit_y / d resid_p) . d_f, a first-order estimate of the ablation.
  * activation only (baseline): act.
Agreement with the ablation is measured per case by Spearman correlation and by whether the top
candidate (largest |value|) matches; a random ordering is reported as the floor.

Uses the exported (float16) model and SAE, i.e. what the browser runs.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from .export import load_exported, load_exported_sae
from .sae import story_windows
from .train import load_tokens

WINDOW = 8


def feature_vectors(sae) -> torch.Tensor:
    """d_f for every feature: what one unit of activation adds to the residual stream."""
    return sae.W_dec.detach() / sae.cfg.scale


@torch.no_grad()
def candidates(model, sae, ids: list[int], t: int, window: int = WINDOW) -> list[tuple[int, int, float]]:
    """(position, feature, activation) for features active at positions max(1, t-window+1)..t."""
    resid = model.resid_at(torch.tensor([ids[: t + 1]]), sae.cfg.layer)[0]
    codes = sae.encode(resid)
    out = []
    for p in range(max(1, t - window + 1), t + 1):
        for f in codes[p].nonzero().flatten().tolist():
            out.append((p, f, float(codes[p, f])))
    return out


@torch.no_grad()
def ablation_effects(model, sae, ids: list[int], t: int, y: int, cands, batch: int = 64) -> np.ndarray:
    """logit_y(clean) - logit_y(feature removed at its position), for each candidate."""
    seq = torch.tensor([ids[: t + 1]])
    clean = model(seq)[0][0, t, y].item()
    D = feature_vectors(sae)
    out = []
    for i in range(0, len(cands), batch):
        chunk = cands[i : i + batch]
        delta = torch.zeros(len(chunk), t + 1, model.cfg.d_model)
        for j, (p, f, act) in enumerate(chunk):
            delta[j, p] = -act * D[f]
        logits, _ = model(seq.expand(len(chunk), -1), resid_hooks={sae.cfg.layer: lambda x, dl=delta: x + dl})
        out.append(clean - logits[:, t, y])
    return torch.cat(out).numpy() if out else np.zeros(0)


def gradient_x_activation(model, sae, ids: list[int], t: int, y: int, cands) -> np.ndarray:
    seq = torch.tensor([ids[: t + 1]])
    captured = {}

    def hook(x):
        x = x.detach().requires_grad_(True)
        captured["x"] = x
        return x

    logits, _ = model(seq, resid_hooks={sae.cfg.layer: hook})
    logits[0, t, y].backward()
    grad = captured["x"].grad[0]
    D = feature_vectors(sae)
    return np.array([act * float(grad[p] @ D[f]) for p, f, act in cands])


@torch.no_grad()
def direct_logit_attribution(model, sae, ids: list[int], t: int, y: int, cands) -> np.ndarray:
    final = model.resid_at(torch.tensor([ids[: t + 1]]), model.cfg.n_layer)[0, t]
    sigma = torch.sqrt(final.var(unbiased=False) + model.cfg.ln_eps)
    readout = model.ln_f.weight * model.wte.weight[y] / sigma  # d logit_y / d (centred residual)
    D = feature_vectors(sae)
    return np.array([act * float((D[f] - D[f].mean()) @ readout) if p == t else 0.0 for p, f, act in cands])


def spearman(a: np.ndarray, b: np.ndarray) -> float:
    ra = np.argsort(np.argsort(a, kind="stable"), kind="stable").astype(float)
    rb = np.argsort(np.argsort(b, kind="stable"), kind="stable").astype(float)
    ra -= ra.mean()
    rb -= rb.mean()
    denom = np.sqrt((ra ** 2).sum() * (rb ** 2).sum())
    return float((ra * rb).sum() / denom) if denom > 0 else 0.0


def write_markdown(r: dict, path: Path) -> None:
    lines = [
        "# Milestone 4: feature attribution, checked by ablation",
        "",
        "Generated by `python -m glassbox.attribution`. Do not edit by hand.",
        "",
        f"{r['cases']} cases from validation stories: the model reads a story up to a random position t and "
        "predicts the actual next token. Candidates are the SAE features active at the last "
        f"{r['window']} positions (mean {r['mean_candidates']:.1f} per case). Ground truth: remove one feature's "
        "contribution from the residual stream and measure the drop in the target token's logit.",
        "",
        "## How well each estimate predicts the ablation",
        "",
        "| estimate | mean Spearman correlation | top candidate matches |",
        "|---|---:|---:|",
    ]
    for name, m in r["estimates"].items():
        lines.append(f"| {name} | {m['spearman']:.3f} | {m['top1']:.1%} |")
    s = r["effects"]
    lines += [
        "",
        "## What the ablations show",
        "",
        f"- Share of the total |effect| that comes from features at the predicting position t: "
        f"{s['share_at_t']:.1%} (the rest comes through attention from earlier positions).",
        f"- Median |effect| of a candidate: {s['median_abs']:.3f} logits; the largest per case has median "
        f"{s['median_max_abs']:.3f}.",
        f"- Candidates that push the target up (effect > 0): {s['share_positive']:.1%}.",
        "",
        "DLA is the estimate named in the project brief; it only sees the direct path from the feature to the "
        "output, so it cannot credit features at earlier positions and ignores blocks after the SAE's layer. "
        "The browser's circuit graph therefore uses ablation itself, which is exact.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--model-dir", type=Path, default=Path("web/model"))
    p.add_argument("--sae-dir", type=Path, default=Path("web/model/sae"))
    p.add_argument("--data-dir", type=Path, default=Path("data/tinystories"))
    p.add_argument("--results-dir", type=Path, default=Path("results"))
    p.add_argument("--cases", type=int, default=300)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--threads", type=int, default=4)
    a = p.parse_args()
    torch.set_num_threads(a.threads)
    t0 = time.time()

    model, tok, _ = load_exported(a.model_dir)
    sae, _ = load_exported_sae(a.sae_dir)
    T = model.cfg.n_ctx
    x, y = story_windows(load_tokens(a.data_dir / "val.bin"), tok.eot_id, T, a.cases)
    rng = np.random.default_rng(a.seed)

    names = ["direct logit attribution", "gradient x activation", "activation only (baseline)",
             "random order (floor)"]
    scores = {n: {"spearman": [], "top1": []} for n in names}
    n_cands, at_t, total_abs, max_abs, all_effects = [], 0.0, 0.0, [], []
    for w in range(len(x)):
        t = int(rng.integers(WINDOW, 160))
        ids, target = x[w].tolist(), int(y[w, t])
        cands = candidates(model, sae, ids, t)
        if len(cands) < 3:
            continue
        effect = ablation_effects(model, sae, ids, t, target, cands)
        estimates = {
            names[0]: direct_logit_attribution(model, sae, ids, t, target, cands),
            names[1]: gradient_x_activation(model, sae, ids, t, target, cands),
            names[2]: np.array([act for _, _, act in cands]),
            names[3]: rng.permutation(len(cands)).astype(float),
        }
        true_top = int(np.argmax(np.abs(effect)))
        for n, est in estimates.items():
            scores[n]["spearman"].append(spearman(est, effect))
            scores[n]["top1"].append(int(np.argmax(np.abs(est))) == true_top)
        n_cands.append(len(cands))
        at_t += float(np.abs(effect[[p == t for p, _, _ in cands]]).sum())
        total_abs += float(np.abs(effect).sum())
        max_abs.append(float(np.abs(effect).max()))
        all_effects.append(effect)

    effects = np.concatenate(all_effects)
    report = {
        "cases": len(n_cands), "window": WINDOW, "mean_candidates": float(np.mean(n_cands)), "seed": a.seed,
        "estimates": {n: {"spearman": float(np.mean(v["spearman"])), "top1": float(np.mean(v["top1"]))}
                      for n, v in scores.items()},
        "effects": {"share_at_t": at_t / total_abs, "median_abs": float(np.median(np.abs(effects))),
                    "median_max_abs": float(np.median(max_abs)), "share_positive": float((effects > 0).mean())},
        "seconds": round(time.time() - t0, 1),
    }
    a.results_dir.mkdir(parents=True, exist_ok=True)
    (a.results_dir / "attribution.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_markdown(report, a.results_dir / "attribution.md")
    for n, m in report["estimates"].items():
        print(f"{n:28s} spearman {m['spearman']:.3f} | top-1 {m['top1']:.1%}")
    print(f"wrote {a.results_dir / 'attribution.md'} in {report['seconds']} s")


if __name__ == "__main__":
    main()
