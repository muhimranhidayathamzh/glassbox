"""Write the results section of README.md from results/*.json, so no number in the README is typed
by hand.

    python -m glassbox.eval.summary            # rewrite the block between the markers
    python -m glassbox.eval.summary --check    # exit 1 if README.md is out of date (used in CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

START, END = "<!-- results:start -->", "<!-- results:end -->"


def load(results: Path, name: str) -> dict:
    return json.loads((results / f"{name}.json").read_text(encoding="utf-8"))


def pct(x: float, digits: int = 0) -> str:
    return f"{x * 100:.{digits}f}%"


def build(results: Path) -> str:
    lm, web, sae, feats = (load(results, n) for n in ("lm_eval", "web_parity", "sae_eval", "sae_features"))
    steer, attr, ind, guard = (load(results, n) for n in ("steering", "attribution", "induction", "guard"))
    t, b = lm["training"], lm["val_loss"]
    sel = next(s for s in sae["saes"] if s["k"] == sae["selected"]["k"])
    spec = feats["token_specificity"]
    spec_other = max(v["share_ge_0.5"] for k, v in spec.items() if k != "SAE (trained)")
    s05 = next(s for s in steer["summary"]["by_alpha"] if s["alpha"] == 0.5)
    est = attr["estimates"]
    f = ind["formation"]
    gm = {m["name"]: m for m in guard["methods"]}
    regex, sae_g, both = gm["regex + name list"], gm["SAE-feature classifier"], gm["regex or SAE guard"]
    strict = gm["regex or SAE guard, strict"]
    js = web["js_vs_torch"]

    lines = [
        START,
        "<!-- Generated by `python -m glassbox.eval.summary` from results/*.json. Do not edit by hand. -->",
        "",
        "| layer | result | report |",
        "|---|---|---|",
        f"| Model from scratch | {lm['n_params'] / 1e6:.1f}M-parameter transformer trained on CPU in "
        f"{t['time']['active_s'] / 3600:.1f} h ({t['tokens_seen'] / 1e6:.1f}M tokens). Validation loss "
        f"**{b['model']:.3f}** vs {b['bigram']:.3f} for a bigram model and {b['unigram']:.3f} for unigram. "
        "| [lm_eval](results/lm_eval.md) |",
        f"| Browser engine | JavaScript forward pass matches PyTorch to {js['max_abs_diff']:.1e} in the logits; "
        f"{web['tokenizer']['identical']:,}/{web['tokenizer']['stories']:,} stories tokenize identically; "
        f"~{web['speed']['generate_tokens_per_s']:.0f} tokens/s in Node.js. "
        "| [web_parity](results/web_parity.md) |",
        f"| Sparse autoencoder | k = {sel['k']}, {sae['n_features']:,} features: variance explained "
        f"{sel['variance_explained']:.3f}, loss +{pct(sel['relative_loss_increase'], 1)} when spliced in "
        f"(PCA with the same k: +{sel['pca_loss_increase']:.2f} nats). {pct(spec['SAE (trained)']['share_ge_0.5'])} "
        "of features have most of their strongest examples on one token, vs at most "
        f"{pct(spec_other)} for residual dimensions, random directions or an untrained SAE. "
        "| [sae_eval](results/sae_eval.md), [sae_features](results/sae_features.md) |",
        f"| Steering | Feature directions at strength 0.5 make {pct(s05['feature_mention'])} of stories mention the "
        f"concept, vs {pct(s05['random_mention'])} for random directions of the same size "
        f"({pct(steer['summary']['alpha_0_mention'])} without steering), at a cost in fluency. "
        "| [steering](results/steering.md) |",
        f"| Attribution | Against ablation, gradient x activation ranks features best (Spearman "
        f"{est['gradient x activation']['spearman']:.2f}); direct logit attribution "
        f"{est['direct logit attribution']['spearman']:.2f}, because {pct(1 - attr['effects']['share_at_t'])} of "
        "the effect flows through attention from earlier positions. | [attribution](results/attribution.md) |",
        f"| Training replay | {len(ind['checkpoints'])} checkpoints. **No induction head formed**: "
        "best prefix-matching "
        f"score {f['final_score']:.3f} (threshold {ind['induction_threshold']}), while a control model reaches "
        f"{ind['control_fixed'][-1]['best_prefix']:.2f}. | [induction](results/induction.md) |",
        f"| Name guard | On names never seen in fitting: regex + name list F1 {regex['new']['f1']:.2f} (recall "
        f"{pct(regex['new']['recall'])}); SAE-feature guard alone F1 {sae_g['new']['f1']:.2f}; **regex or SAE guard "
        f"catches {pct(both['new']['recall'])} of names** ({pct(strict['new']['recall'])} in strict mode), at "
        f"{both['new']['false_blocks_per_1000_tokens']:.0f} false blocks per 1,000 tokens; +"
        f"{guard['latency']['added_ms']['SAE guard + word check']:.2f} ms per token. | [guard](results/guard.md) |",
        "",
        "### Negative and mixed results, reported as they came out",
        "",
        f"- **No induction heads** in this {lm['n_params'] / 1e6:.1f}M-parameter model after "
        f"{t['tokens_seen'] / 1e6:.1f}M tokens, on random, frequent and natural repeated text alike. The probe "
        "works (positive control), so this is a property of the model and its training budget.",
        f"- **The SAE guard does not beat a regex** on its own (F1 {sae_g['new']['f1']:.2f} vs "
        f"{regex['new']['f1']:.2f}): predicting a name before it is written is inherently uncertain. Its value is "
        "complementary: it catches names at the start of sentences that a regex cannot see.",
        f"- **The SAE used by the UI raises the model's loss by {pct(sel['relative_loss_increase'], 1)}** when "
        "spliced in, and "
        f"{pct(sel['dead'] / sae['n_features'])} of its features are dead. It was chosen by a rule fixed in "
        "advance that turned out to be lenient.",
        f"- **Direct logit attribution**, the method named in the project brief, correlates weakly with the "
        f"true effect of removing a feature (Spearman {est['direct logit attribution']['spearman']:.2f}).",
        END,
    ]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--readme", type=Path, default=Path("README.md"))
    p.add_argument("--results-dir", type=Path, default=Path("results"))
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = a.readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"{a.readme} has no {START} ... {END} block")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    updated = head + build(a.results_dir) + tail
    if a.check:
        if updated != text:
            sys.exit(f"{a.readme} is out of date: run python -m glassbox.eval.summary")
        print(f"{a.readme} is up to date")
        return
    a.readme.write_text(updated, encoding="utf-8")
    print(f"updated {a.readme}")


if __name__ == "__main__":
    main()
