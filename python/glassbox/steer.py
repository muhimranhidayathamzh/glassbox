"""Steering: add a direction to the residual stream while the model writes, and measure whether
SAE feature directions steer better than random directions of the same size.

    python -m glassbox.steer        # -> results/steering.{json,md}, web/model/sae/steering.json

    v = alpha * resid_norm * u      added at the SAE's layer, at every position >= 1

u is a unit vector: an SAE decoder direction, or a random direction. resid_norm is the mean
norm of the residual stream at that layer, so alpha = 1 adds a vector as large as a typical
residual. Uses the exported (float16) model and SAE, i.e. what the browser runs.

Fixed before any result was seen: the concept words, the rule that picks one feature per word,
the alphas, the prompts and seeds, and the number of random directions.
"""

from __future__ import annotations

import argparse
import json
import re
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

from .export import load_exported, load_exported_sae
from .sae import story_windows
from .tokenizer import BPETokenizer
from .train import load_tokens

CONCEPTS = ["ball", "dog", "cat", "tree", "rain", "cake", "car", "flower"]
ALPHAS = [0.25, 0.5, 1.0, 2.0]
N_RANDOM = 4
PROMPTS = ["Once upon a time", "One day, Lily went to the", "Tom and his mom"]
SEEDS_PER_PROMPT = 16
MAX_NEW_TOKENS = 60
TEMPERATURE, TOP_K = 0.8, 50
MIN_EXAMPLES = 10


def feature_direction(sae, f: int) -> torch.Tensor:
    """Unit vector in residual-stream space along feature f's decoder direction."""
    d = sae.W_dec[f].detach() / sae.cfg.scale
    return d / d.norm()


def steering_hook(vec: torch.Tensor):
    """Add vec to the residual stream at every position >= 1 (position 0 is <|endoftext|>)."""
    return lambda x: torch.cat([x[:, :1], x[:, 1:] + vec], dim=1)


def pick_feature(features: list[dict], tok: BPETokenizer, word: str) -> dict | None:
    """The live feature labelled with the token " word" itself, with at least MIN_EXAMPLES distinct
    examples; ties broken by label share, then density. None if there is no such feature."""
    ids = tok.encode(" " + word)
    if len(ids) != 1:
        return None
    cands = [f for f in features if not f.get("dead") and f["label_kind"] == "token"
             and f["label_token"] == ids[0] and f["n_examples"] >= MIN_EXAMPLES]
    return max(cands, key=lambda f: (f["label_share"], f["density"]), default=None)


def mentions(text: str, word: str) -> bool:
    return re.search(rf"\b{re.escape(word)}s?\b", text, flags=re.IGNORECASE) is not None


@torch.no_grad()
def generate_batch(model, prompt: list[int], n: int, seed: int, hooks=None, eot: int | None = None) -> list[list[int]]:
    """n sampled continuations of the same prompt, cut at <|endoftext|>."""
    g = torch.Generator().manual_seed(seed)
    idx = torch.tensor([prompt] * n)
    for _ in range(MAX_NEW_TOKENS):
        logits, _ = model(idx, resid_hooks=hooks)
        logits = logits[:, -1] / TEMPERATURE
        kth = torch.topk(logits, TOP_K).values[:, -1:]
        probs = torch.softmax(logits.masked_fill(logits < kth, float("-inf")), dim=-1)
        idx = torch.cat([idx, torch.multinomial(probs, 1, generator=g)], dim=1)
    out = []
    for row in idx[:, len(prompt):].tolist():
        out.append(row[: row.index(eot)] if eot is not None and eot in row else row)
    return out


@torch.no_grad()
def continuation_nll(model, prompt: list[int], conts: list[list[int]]) -> tuple[float, int]:
    """Total NLL (nats) and token count of the continuations under the unsteered model."""
    total, count = 0.0, 0
    for c in conts:
        if not c:
            continue
        ids = torch.tensor([prompt + c])
        logits, _ = model(ids[:, :-1])
        targets = ids[0, len(prompt):]
        total += F.cross_entropy(logits[0, len(prompt) - 1 :], targets, reduction="sum").item()
        count += len(c)
    return total, count


def run_condition(model, tok, prompts: list[list[int]], hooks) -> dict:
    texts, nll, count = [], 0.0, 0
    for i, prompt in enumerate(prompts):
        conts = generate_batch(model, prompt, SEEDS_PER_PROMPT, seed=1000 + i, hooks=hooks, eot=tok.eot_id)
        texts += [tok.decode(c) for c in conts]
        t, c = continuation_nll(model, prompt, conts)
        nll, count = nll + t, count + c
    return {"texts": texts, "nll": nll / max(count, 1)}


def write_markdown(r: dict, path: Path) -> None:
    n = r["samples_per_condition"]
    lines = [
        "# Milestone 4: steering with SAE features",
        "",
        "Generated by `python -m glassbox.steer`. Do not edit by hand.",
        "",
        f"A vector alpha x {r['resid_norm']:.1f} x u is added to the residual stream entering block {r['layer']} "
        f"at every position >= 1, where {r['resid_norm']:.1f} is the mean residual norm there and u is a unit "
        "vector: the decoder direction of the concept's SAE feature, or one of "
        f"{r['n_random']} random directions. Each condition: {n} stories ({len(r['prompts'])} prompts x "
        f"{n // len(r['prompts'])} seeds, the same seeds in every condition), up to {r['max_new_tokens']} new "
        f"tokens, temperature {r['temperature']}, top-k {r['top_k']}.",
        "",
        "- **mention rate**: share of stories that contain the concept word (or its plural)",
        "- **NLL**: loss of the generated continuation under the unsteered model, in nats/token; higher means "
        "less natural text",
        "",
        "Concept words, the feature-selection rule, alphas, prompts and seeds were fixed before any result was "
        "seen. Feature rule: the live feature whose automatic label is the word's token itself, with at least "
        f"{r['min_examples']} distinct examples; highest label share wins.",
        "",
        "## Summary (mean over concepts)",
        "",
        f"Without steering (alpha 0) the mean mention rate is {r['summary']['alpha_0_mention']:.1%} "
        f"and the NLL is {r['summary']['alpha_0_nll']:.3f}.",
        "",
        "| alpha | mention rate, feature | mention rate, random | NLL, feature | NLL, random |",
        "|---:|---:|---:|---:|---:|",
    ]
    for s in r["summary"]["by_alpha"]:
        lines.append(f"| {s['alpha']:g} | {s['feature_mention']:.1%} | {s['random_mention']:.1%} | "
                     f"{s['feature_nll']:.3f} | {s['random_nll']:.3f} |")
    lines += ["", "## Per concept", "",
              "Mention rate with the feature direction; in brackets the mean over the random directions "
              "(the same random directions are used for every concept).", ""]
    header = "| concept | feature | alpha 0 | " + " | ".join(f"alpha {a:g}" for a in r["alphas"]) + " |"
    lines += [header, "|---|---|---:|" + "---:|" * len(r["alphas"])]
    for c in r["concepts"]:
        if c["feature"] is None:
            lines.append(f"| {c['word']} | no feature matches the rule | {c['alpha_0']:.0%} |"
                         + " - |" * len(r["alphas"]))
            continue
        cells = [f"{c['feature_mention'][i]:.0%} ({c['random_mention'][i]:.0%})" for i in range(len(r["alphas"]))]
        lines.append(f"| {c['word']} | #{c['feature']} `{c['label']}` | {c['alpha_0']:.0%} | "
                     + " | ".join(cells) + " |")
    ex = r["example"]
    lines += [
        "",
        f"## One steered story (not cherry-picked: concept `{ex['word']}`, alpha {ex['alpha']:g}, first seed of "
        "the first prompt)",
        "",
        "Without steering:",
        "",
        "```text",
        ex["plain"],
        "```",
        "",
        "With steering:",
        "",
        "```text",
        ex["steered"],
        "```",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--model-dir", type=Path, default=Path("web/model"))
    p.add_argument("--sae-dir", type=Path, default=Path("web/model/sae"))
    p.add_argument("--data-dir", type=Path, default=Path("data/tinystories"))
    p.add_argument("--results-dir", type=Path, default=Path("results"))
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--threads", type=int, default=4)
    a = p.parse_args()
    torch.set_num_threads(a.threads)
    t0 = time.time()

    model, tok, _ = load_exported(a.model_dir)
    sae, sae_manifest = load_exported_sae(a.sae_dir)
    features = json.loads((a.sae_dir / "features.json").read_text(encoding="utf-8"))["features"]
    layer, d = sae.cfg.layer, model.cfg.d_model

    x, _ = story_windows(load_tokens(a.data_dir / "val.bin"), tok.eot_id, model.cfg.n_ctx, 64)
    with torch.no_grad():
        resid_norm = float(model.resid_at(torch.from_numpy(x), layer)[:, 1:].norm(dim=-1).mean())
    g = torch.Generator().manual_seed(a.seed)
    randoms = torch.randn(N_RANDOM, d, generator=g)
    randoms /= randoms.norm(dim=1, keepdim=True)
    prompts = [[tok.eot_id] + tok.encode(pr) for pr in PROMPTS]

    def texts_for(u, alpha):
        hooks = {layer: steering_hook(alpha * resid_norm * u)} if u is not None else None
        return run_condition(model, tok, prompts, hooks)

    def rate(texts, word):
        return float(np.mean([mentions(t, word) for t in texts]))

    base = texts_for(None, 0.0)
    random_runs = {(i, al): texts_for(randoms[i], al) for i in range(N_RANDOM) for al in ALPHAS}
    concepts, example = [], None
    for word in CONCEPTS:
        feat = pick_feature(features, tok, word)
        c = {"word": word, "feature": feat["id"] if feat else None, "label": feat["label"] if feat else None,
             "alpha_0": rate(base["texts"], word),
             "random_mention": [float(np.mean([rate(random_runs[(i, al)]["texts"], word) for i in range(N_RANDOM)]))
                                for al in ALPHAS],
             "random_nll": [float(np.mean([random_runs[(i, al)]["nll"] for i in range(N_RANDOM)])) for al in ALPHAS]}
        if feat:
            u = feature_direction(sae, feat["id"])
            runs = [texts_for(u, al) for al in ALPHAS]
            c["feature_mention"] = [rate(rr["texts"], word) for rr in runs]
            c["feature_nll"] = [rr["nll"] for rr in runs]
            if example is None:
                mid = ALPHAS.index(1.0)
                example = {"word": word, "alpha": ALPHAS[mid], "plain": PROMPTS[0] + base["texts"][0],
                           "steered": PROMPTS[0] + runs[mid]["texts"][0]}
        concepts.append(c)
        feature_rates = [f"{v:.0%}" for v in c.get("feature_mention", [])]
        random_rates = [f"{v:.0%}" for v in c["random_mention"]]
        print(f"{word}: feature {c['feature']} | alpha 0 {c['alpha_0']:.0%} | feature {feature_rates} "
              f"| random {random_rates}", flush=True)

    steered = [c for c in concepts if c["feature"] is not None]
    summary = {
        "concepts_with_feature": len(steered),
        "alpha_0_mention": float(np.mean([c["alpha_0"] for c in steered])),
        "alpha_0_nll": base["nll"],
        "by_alpha": [
            {"alpha": al,
             "feature_mention": float(np.mean([c["feature_mention"][i] for c in steered])),
             "random_mention": float(np.mean([c["random_mention"][i] for c in steered])),
             "feature_nll": float(np.mean([c["feature_nll"][i] for c in steered])),
             "random_nll": float(np.mean([c["random_nll"][i] for c in steered]))}
            for i, al in enumerate(ALPHAS)
        ],
    }
    report = {
        "layer": layer, "resid_norm": resid_norm, "alphas": ALPHAS, "n_random": N_RANDOM, "prompts": PROMPTS,
        "samples_per_condition": len(PROMPTS) * SEEDS_PER_PROMPT, "max_new_tokens": MAX_NEW_TOKENS,
        "temperature": TEMPERATURE, "top_k": TOP_K, "min_examples": MIN_EXAMPLES, "seed": a.seed,
        "sae": sae_manifest["config"], "concepts": concepts, "summary": summary, "example": example,
        "seconds": round(time.time() - t0, 1),
    }
    a.results_dir.mkdir(parents=True, exist_ok=True)
    (a.results_dir / "steering.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_markdown(report, a.results_dir / "steering.md")
    ui = {"format": "glassbox-steering", "version": 1, "layer": layer, "resid_norm": resid_norm,
          "sae_weights_sha256": sae_manifest["weights_sha256"], "max_alpha": max(ALPHAS) * 2,
          "presets": [{"word": c["word"], "feature": c["feature"], "label": c["label"]} for c in steered]}
    (a.sae_dir / "steering.json").write_text(json.dumps(ui, indent=1), encoding="utf-8")
    print(f"wrote {a.results_dir / 'steering.md'} and {a.sae_dir / 'steering.json'} in {report['seconds']} s")


if __name__ == "__main__":
    main()
