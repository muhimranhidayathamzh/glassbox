"""Which internal signal is best for the name guard? SAE features of different sparsity, and the raw
residual stream at every layer, compared with a protocol that never looks at the test data to choose.

    python -m glassbox.guard_layers      # -> results/guard_layers.{json,md}; may replace web/model/guard.json

Protocol (fixed before running):
  * fit split: the first FIT_STORIES calibration stories of guard.py, with their own (known) names
  * selection split: the remaining calibration stories, names replaced by new names from pool A
  * test: guard.py's test stories, with known names, and with new names from pool B (disjoint from A)
Every candidate is fitted on the fit split; its threshold is the best-F1 threshold on the selection
split. The guard used by the web page reads SAE features (so each block can be explained by feature
labels): it switches to another SAE only if that SAE's classifier has a higher selection F1 than the
current one (k = 8). Residual-stream probes are reported as a reference for where the information is.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from .data import TRAIN_HEAD_NAME, VALID_FILE, split_stories
from .export import load_exported, load_exported_sae
from .guard import (
    NEW_NAMES,
    STRICT_RECALL,
    BagLR,
    Example,
    Features,
    best_threshold,
    build_lexicon,
    fit_logreg,
    has_unknown_capitals,
    label_story,
    metrics,
    name_spans,
    recall_threshold,
    regex_flags,
    substitute,
)

FIT_STORIES = 1000
CURRENT_GUARD = "sae"  # web/model/sae, the SAE the page's guard uses now


def kept_positions(e: Example) -> list[int]:
    return [t for t, lab in enumerate(e.labels) if lab != -1]


@torch.no_grad()
def residuals(model, examples: list[Example], layer: int, batch: int = 16) -> np.ndarray:
    out = []
    for i in range(0, len(examples), batch):
        chunk = examples[i : i + batch]
        T = max(len(e.ids) for e in chunk)
        r = model.resid_at(torch.tensor([e.ids + [0] * (T - len(e.ids)) for e in chunk]), layer)
        out += [r[b, kept_positions(e)].numpy() for b, e in enumerate(chunk)]
    return np.concatenate(out)


@torch.no_grad()
def sae_codes(model, sae, examples: list[Example], batch: int = 16) -> tuple[np.ndarray, np.ndarray]:
    idx, val = [], []
    for i in range(0, len(examples), batch):
        chunk = examples[i : i + batch]
        T = max(len(e.ids) for e in chunk)
        codes = sae.encode(model.resid_at(torch.tensor([e.ids + [0] * (T - len(e.ids)) for e in chunk]),
                                          sae.cfg.layer))
        codes[:, 0] = 0  # position 0 is skipped by every SAE
        top = codes.topk(sae.cfg.k, dim=-1)
        for b, e in enumerate(chunk):
            keep = kept_positions(e)
            idx.append(top.indices[b, keep].numpy())
            val.append(top.values[b, keep].numpy())
    return np.concatenate(idx), np.concatenate(val)


def text_view(examples: list[Example]) -> Features:
    """Labels and next words only (what the regex needs)."""
    y, words, sent = [], [], []
    for e in examples:
        for t in kept_positions(e):
            y.append(e.labels[t])
            words.append(e.next_word[t])
            sent.append(e.next_sentence_start[t])
    return Features(None, None, None, None, None, np.array(y), words, np.array(sent))


class DenseProbe:
    def __init__(self, x: np.ndarray, y: np.ndarray):
        self.mean, self.std = x.mean(0), x.std(0) + 1e-6
        self.w = torch.zeros(x.shape[1], requires_grad=True)
        self.b = torch.zeros((), requires_grad=True)
        xt = torch.from_numpy((x - self.mean) / self.std)
        fit_logreg(lambda: xt @ self.w + self.b, [self.w, self.b], y)

    @torch.no_grad()
    def scores(self, x: np.ndarray) -> np.ndarray:
        return (torch.from_numpy((x - self.mean) / self.std) @ self.w + self.b).numpy()


def evaluate(name: str, kind: str, sel_scores, test_scores: dict, views: dict, names: set) -> dict:
    sel = views["selection"]
    th = best_threshold(sel_scores, sel.y)
    row = {"name": name, "input": kind, "threshold": th, "strict_threshold": recall_threshold(sel_scores, sel.y,
                                                                                               STRICT_RECALL),
           "selection": metrics(sel_scores >= th, sel.y)}
    for cond in ("known", "new"):
        v = views[cond]
        pred = test_scores[cond] >= th
        row[cond] = metrics(pred, v.y)
        row[f"regex_or_{cond}"] = metrics(regex_flags(v, names) | pred, v.y)
    return row


def write_markdown(r: dict, path: Path) -> None:
    lines = [
        "# Name guard: which internal signal works best?",
        "",
        "Generated by `python -m glassbox.guard_layers`. Do not edit by hand.",
        "",
        "Protocol fixed before running: every candidate is fitted on "
        f"{r['fit_stories']:,} calibration stories (known names); its threshold is the best-F1 threshold on "
        f"{r['selection_stories']:,} other calibration stories whose names were replaced by new names from pool A "
        f"({', '.join(r['pool_a'][:5])}, ...). The test stories ({r['test_stories']:,}) are scored once, with "
        f"known names and with new names from pool B ({', '.join(r['pool_b'][:5])}, ...), which never appears "
        "before the test. The page's guard reads SAE features and switches SAE only if another SAE wins on the "
        "selection split; residual-stream probes are a reference.",
        "",
        "| candidate | reads | selection F1 (new names A) | test F1, known | test F1, new names B | "
        "test recall, new B | regex or candidate: recall, new B | F1 | false blocks / 1000 tokens |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for c in r["candidates"]:
        mark = " **(selected)**" if c["name"] == r["selected"] else ""
        both = c["regex_or_new"]
        lines.append(
            f"| {c['name']}{mark} | {c['input']} | {c['selection']['f1']:.3f} | {c['known']['f1']:.3f} | "
            f"{c['new']['f1']:.3f} | {c['new']['recall']:.3f} | {both['recall']:.3f} | {both['f1']:.3f} | "
            f"{both['false_blocks_per_1000_tokens']:.1f} |"
        )
    rx = r["regex"]
    lines += [
        f"| regex + name list alone | the chosen word | - | {rx['known']['f1']:.3f} | {rx['new']['f1']:.3f} | "
        f"{rx['new']['recall']:.3f} | - | - | {rx['new']['false_blocks_per_1000_tokens']:.1f} |",
        "",
        f"**Rule outcome:** {r['decision']}",
        "",
        f"Best residual-stream layer on the selection split: {r['best_residual']} (reference only: it reads the raw "
        "internal state, so its blocks cannot be explained by feature labels).",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--model-dir", type=Path, default=Path("web/model"))
    p.add_argument("--raw-dir", type=Path, default=Path("data/raw"))
    p.add_argument("--results-dir", type=Path, default=Path("results"))
    p.add_argument("--calibration-stories", type=int, default=1500)
    p.add_argument("--test-stories", type=int, default=1500)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--threads", type=int, default=4)
    a = p.parse_args()
    torch.set_num_threads(a.threads)
    torch.manual_seed(a.seed)
    t0 = time.time()

    model, tok, _ = load_exported(a.model_dir)
    T = model.cfg.n_ctx
    train_stories, _ = split_stories((a.raw_dir / TRAIN_HEAD_NAME).read_text(encoding="utf-8"))
    names, cap_counts = build_lexicon(train_stories)
    pool = [n for n in NEW_NAMES if n not in names and cap_counts[n] < 5]
    pool_a, pool_b = pool[0::2], pool[1::2]
    val_stories, _ = split_stories((a.raw_dir / VALID_FILE).read_text(encoding="utf-8"))
    kept = [s for s in val_stories if not has_unknown_capitals(s, names)]
    cal = kept[: a.calibration_stories]
    test = kept[a.calibration_stories : a.calibration_stories + a.test_stories]
    rng = np.random.default_rng(a.seed)

    def substituted(stories, names_pool):
        out = []
        for s in stories:
            s2, used = substitute(s, names, names_pool, rng)
            out.append(label_story(tok, s2, name_spans(s2, used), T))
        return out

    sets = {
        "fit": [label_story(tok, s, name_spans(s, names), T) for s in cal[:FIT_STORIES]],
        "selection": substituted(cal[FIT_STORIES:], pool_a),
        "known": [label_story(tok, s, name_spans(s, names), T) for s in test],
        "new": substituted(test, pool_b),
    }
    views = {k: text_view(v) for k, v in sets.items()}
    print({k: (len(v.y), int((v.y == 1).sum())) for k, v in views.items()}, flush=True)

    candidates = []
    sae_dirs = sorted(d for d in a.model_dir.glob("sae*") if (d / "manifest.json").exists())
    for d in sae_dirs:
        sae, _ = load_exported_sae(d)
        fit_i, fit_v = sae_codes(model, sae, sets["fit"])
        lr = BagLR(sae.cfg.n_features, fit_i, fit_v, views["fit"].y)
        scores = {k: lr.scores(*sae_codes(model, sae, sets[k])) for k in ("selection", "known", "new")}
        name = f"SAE features, k = {sae.cfg.k} ({d.name})"
        row = evaluate(name, f"SAE layer {sae.cfg.layer}", scores["selection"],
                       {c: scores[c] for c in ("known", "new")}, views, names)
        row.update({"dir": d.name, "k": sae.cfg.k, "bias": float(lr.b),
                    "weights": [round(float(v), 5) for v in lr.w.detach().numpy()]})
        candidates.append(row)
        print(f"{name}: selection F1 {row['selection']['f1']:.3f} | test new {row['new']['f1']:.3f}", flush=True)
    for layer in range(model.cfg.n_layer + 1):
        probe = DenseProbe(residuals(model, sets["fit"], layer), views["fit"].y)
        scores = {k: probe.scores(residuals(model, sets[k], layer)) for k in ("selection", "known", "new")}
        row = evaluate(f"residual stream, layer {layer}", "raw residual", scores["selection"],
                       {c: scores[c] for c in ("known", "new")}, views, names)
        candidates.append(row)
        print(f"residual layer {layer}: selection F1 {row['selection']['f1']:.3f} | test new {row['new']['f1']:.3f}",
              flush=True)

    sae_rows = [c for c in candidates if "dir" in c]
    current = next(c for c in sae_rows if c["dir"] == CURRENT_GUARD)
    best_sae = max(sae_rows, key=lambda c: c["selection"]["f1"])
    switch = best_sae is not current and best_sae["selection"]["f1"] > current["selection"]["f1"]
    decision = (f"the guard switches to {best_sae['name']} (selection F1 {best_sae['selection']['f1']:.3f} vs "
                f"{current['selection']['f1']:.3f})." if switch else
                f"the guard keeps {current['name']}; no other SAE has a higher selection F1.")
    res_rows = [c for c in candidates if "dir" not in c]
    best_res = max(res_rows, key=lambda c: c["selection"]["f1"])
    report = {
        "fit_stories": FIT_STORIES, "selection_stories": len(sets["selection"]), "test_stories": len(test),
        "pool_a": pool_a, "pool_b": pool_b, "seed": a.seed,
        "candidates": [{k: v for k, v in c.items() if k != "weights"} for c in candidates],
        "regex": {c: metrics(regex_flags(views[c], names), views[c].y) for c in ("known", "new")},
        "selected": best_sae["name"], "switch": switch, "decision": decision, "best_residual": best_res["name"],
        "seconds": round(time.time() - t0, 1),
    }
    a.results_dir.mkdir(parents=True, exist_ok=True)
    (a.results_dir / "guard_layers.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_markdown(report, a.results_dir / "guard_layers.md")
    if switch:  # the page's guard: fitted on the fit split, thresholds from the selection split
        old = json.loads((a.model_dir / "guard.json").read_text(encoding="utf-8"))
        sae_dir = a.model_dir / best_sae["dir"]
        manifest = json.loads((sae_dir / "manifest.json").read_text(encoding="utf-8"))
        labels = {f["id"]: f.get("label", "?") for f in
                  json.loads((sae_dir / "features.json").read_text(encoding="utf-8"))["features"]}
        w = np.array(best_sae["weights"])
        guard_ui = {
            "format": "glassbox-guard", "version": 1, "layer": manifest["config"]["layer"],
            "sae_dir": best_sae["dir"], "sae_weights_sha256": manifest["weights_sha256"],
            "bias": best_sae["bias"], "threshold": best_sae["threshold"],
            "strict_threshold": best_sae["strict_threshold"], "strict_recall": STRICT_RECALL,
            "names": old["names"], "exclude": old["exclude"], "weights": best_sae["weights"],
            "labels": {str(int(i)): labels.get(int(i), "?") for i in np.nonzero(w > 0.05)[0]},
            "selected_by": "python -m glassbox.guard_layers",
        }
        (a.model_dir / "guard.json").write_text(json.dumps(guard_ui, separators=(",", ":")), encoding="utf-8")
    print(f"{decision} Wrote {a.results_dir / 'guard_layers.md'} in {report['seconds']} s")


if __name__ == "__main__":
    main()
